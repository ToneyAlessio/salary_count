// app.js 是小程序的「总入口」，整个小程序启动时最先执行这里。
// 可以把它理解成整个程序的「大门」，进来的第一件事就是运行这个文件。

App({
    // onLaunch 是一个「生命周期函数」：小程序每次启动时会自动调用一次。
    // 我们暂时只在控制台打一行日志，用来确认它真的跑了。
    onLaunch() {
        console.log('小程序启动了');
    },

    // globalData 用来存放「所有页面都能用到的公共数据」。
    // 现在先放个名字，后面如果多个页面都要用同一份数据，就放这里。
    globalData: {
        appName: '工资计时器',
    },
});
